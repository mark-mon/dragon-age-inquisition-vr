#!/usr/bin/env python3
"""Generate src/fb_table.inc (field tables for the Frostbite settings classes the mod reads / writes at runtime)
from the reflected type dump made by fb_sdk.py.   gen_fbtable.py sdk.txt src/fb_table.inc"""
import sys, re

# class -> RVA of the static pointer the engine caches the settings instance in (found with fb_sdk + code refs)
GLOBALS = {"DxDisplaySettings": 0, "WorldRenderSettings": 0, "GameRenderSettings": 0, "DA3WorldRenderSettings": 0,
           "GlobalPostProcessSettings": 0}   # DAI: instances found at runtime (0 = no static pointer known)
SCALAR = {"Boolean": "B", "Float32": "F", "Int32": "I", "Uint32": "U", "Int8": "i8", "Uint8": "u8", "Int16": "i16", "Uint16": "u16"}

classes, cur = {}, None
for l in open(sys.argv[1]):
    m = re.match(r"(class|struct) (\S+) : (\S*)\s+// size (0x[0-9a-f]+)", l)
    if m: cur = classes.setdefault(m.group(2), {"super": m.group(3), "fields": []}); continue
    m = re.match(r"\s+\+(0x[0-9a-f]+) (\S+) (\S+)", l)
    if m and cur is not None: cur["fields"].append((int(m.group(1), 16), m.group(2), m.group(3)))
enums = set(n for n in classes if False)

def all_fields(c):
    out = []
    while c in classes:
        out = classes[c]["fields"] + out
        c = classes[c]["super"]
    return out

with open(sys.argv[2], "w") as f:
    f.write("// generated by tools/gen_fbtable.py from the game's reflected type data - do not edit\n")
    for cls, rva in GLOBALS.items():
        rows = []
        for off, typ, name in sorted(all_fields(cls)):
            t = SCALAR.get(typ)
            if not t and not typ.endswith("-Array") and typ not in ("CString",) and typ not in classes:
                t = "E"   # enum (4 bytes)
            if t: rows.append(f'    {{"{name}", {off:#x}, "{t}"}},')
        f.write(f'static const FbField kFields_{cls}[] = {{\n' + "\n".join(rows) + "\n};\n")
    f.write("static const FbClass kFbClasses[] = {\n")
    for cls, rva in GLOBALS.items():
        f.write(f'    {{"{cls}", {rva:#x}, kFields_{cls}, sizeof(kFields_{cls}) / sizeof(FbField)}},\n')
    f.write("};\n")
print("ok")
